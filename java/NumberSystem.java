public class NumberSystem {
    public static void main(String[] args) {
        //Decimal number system
        //It contains number from 0-9 , with repetitive digits, the original whole numbers.
        System.out.println(1290+2883);

        //Binary numbers system
        //it contains only 1 and 0 to represent on/off state : to make a binary number use suffix:0b or 0B
        System.out.println(0b101001);

        //Octal numbers system
        //It contains only 0-7, base is 8 . representation : just add 0 as the sufix
        System.out.println(0123 + 01001);

        //Hexadecimal numbers system
        //It contains 0-15 , base 16 with 10->A,11->B...15->F, use suffix : 0x or 0X
        System.out.println(0x182AB28);

        //Anyway the final output of all these are decimal respectively
    }
}
